const router = require('express').Router();
const path = require('path');
const fs = require('fs');
const multer = require('multer');
const controller = require('../controllers/messageController');
const { authenticate, adminOnly } = require('../middleware/auth');
const uploadDir = path.join(__dirname, '..', 'uploads');
fs.mkdirSync(uploadDir, { recursive: true });
const storage = multer.diskStorage({ destination: (_req, _file, cb) => cb(null, uploadDir), filename: (_req, file, cb) => cb(null, `${Date.now()}-${Math.round(Math.random()*1e9)}${path.extname(file.originalname).toLowerCase()}`) });
const upload = multer({ storage, limits: { fileSize: 5 * 1024 * 1024 }, fileFilter: (_req, file, cb) => cb(null, /^image\/(jpeg|png|webp)$/.test(file.mimetype)) });
router.post('/', upload.single('image'), controller.create);
router.get('/', authenticate, adminOnly, controller.list);
router.patch('/:id/status', authenticate, adminOnly, controller.updateStatus);
module.exports = router;
